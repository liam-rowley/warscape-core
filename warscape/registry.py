def _cell(v, code=False):
    if v is None or v == '' or v == []:
        return ''
    if isinstance(v, list):
        s = ', '.join(x if isinstance(x, str) else json.dumps(x, ensure_ascii=False) for x in v)
    elif isinstance(v, dict):
        s = json.dumps(v, ensure_ascii=False)
    elif isinstance(v, bool):
        s = 'yes' if v else 'no'
    else:
        s = str(v)
    s = ' '.join(s.split()).replace('|', '\\|')
    if len(s) > 200:
        s = s[:197] + '...'
    return f'`{s}`' if code and '`' not in s else s


def load_all(ctx):
    """{name: Registry} for every registry the repo declares (raises RegistryError on an unusable schema)."""
    return load_from_config(ctx.config, ctx.root)


def load_from_config(cfg, root, label=None, only=None, storage=None):
    """Registries of a loaded `wsc.toml` config rooted at `root`; `only`: one name; `storage`: force a storage (`reg migrate`)."""
    d, dirs = cfg['registries_dir'], set(cfg['storage']['dir'])
    return {n: Registry(n, spec, root, d, label=label, storage=storage or ('dir' if n in dirs else 'jsonl'), views=cfg['views'])
            for n, spec in cfg['registries'].items() if only is None or n == only}


def core_tools(ctx):
    """The core's own tools registry when running in a game repo (so `find` sees the core's verbs too); None inside the core."""
    if ctx.is_core:
        return None
    from .repo import load_config
    try:
        return load_from_config(load_config(ctx.core_root), ctx.core_root, label='core:tools', only='tools').get('tools')
    except Exception:
        return None
