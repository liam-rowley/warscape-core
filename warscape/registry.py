"""The registry framework: every registry is rows (JSONL, or one file per row) + a JSON Schema + a generated Markdown view + a check.

Files, for a registry named N declared in `wsc.toml` `[registries]`. The rows, the source of truth, are in one of two storages:
  jsonl (default)        <registries_dir>/N.jsonl: one row per line, canonical form (rows sorted by id, keys in schema order)
  dir (`[storage] dir`)  <registries_dir>/N/<file>.json: one row per file, canonical form (keys in schema order, indented two spaces,
                         one trailing newline, so a field change is a one-line diff); <file> is id_to_file(id). Two branches that add
                         or change different rows touch different files, so git merges them with no conflict and no union driver; a
                         duplicate id cannot be stored, and a file whose name and id disagree is an error.
The view, generated by `wsc reg render` (and `reg add|set`); never edit it:
  `[views] commit = true` (default)   <registries_dir>/N.md, committed; the check fails when it is stale
  `[views] commit = false`            <views dir>/N.md (default `_scratch/registries/`, git-ignored); the check only renders it, and
                                      a <registries_dir>/N.md on disk is an error (a stale copy cannot linger)
`wsc reg migrate N --to dir|jsonl` moves a registry between storages and updates `[storage] dir` in `wsc.toml`.
Schema: "core:N" means the core's `schemas/N.schema.json`; anything else is a repo-relative path. Every schema is read through
`load_schema`, which resolves `x-extends`.

Registry extensions in the schema (ignored by the validator):
  x-view:   {"title": str, "columns": [field, ...]}            columns of the generated table (default: id, description)
  x-unique: [[field, ...], ...]                                 field tuples that must be unique across rows (compared case-insensitively)
  x-wildcard: {field: value}                                   a row with this value in an x-unique field clashes with every value
  x-chord:  {"field": f, "flag": g}                             in every x-unique tuple holding f, values of f are `<mod>+...+<key>` chords
                                                                (separator `+`): two rows also clash when one row's g is `any_modifier`, its
                                                                f is a bare key (no `+`) and the other's key (last segment) is the same, or
                                                                its g is `shift`, the keys are the same and the other's modifiers are none
                                                                or exactly Shift (case-insensitive; the other tuple fields and x-wildcard
                                                                apply as usual). The message names the rule: `Alt+Space reaches Space,
                                                                which fires with any modifier`
  x-ref:    on a property: "<registry>"                         the value (or each item of an array) must be an id in that registry
  x-source: "tool-headers"                                      rows are derived from file headers (warscape.tools adds the coverage check)
  x-extends: "core:<name>"                                      top level of a game schema only: the document adds to that core schema,
                                                                merged at load (one level: a core schema never extends, a game schema
                                                                cannot extend a game schema). It may hold only EXTENDS_KEYS; anything else
                                                                (additionalProperties, type, x-wildcard ...) is a load error, and so is an
                                                                x-extends below the top level. Merge: `properties` the core's, then the
                                                                game's in its order (a name the core has is an error: narrow a core
                                                                property with an allOf entry); `required` the union, core order first;
                                                                `allOf` and `x-unique` the core's entries, then the game's; `$defs` merged
                                                                (a clash is an error); `x-view`, `title`, `description`, `$id` the game's
                                                                when given; everything else the core's (so `additionalProperties: false`
                                                                holds over the merged set). Canonical key order follows the merged
                                                                `properties`: core fields first, then the game's. The merged document must
                                                                pass check_schema.
"""
import json
import re
from pathlib import Path
from urllib.parse import quote, unquote

from . import CORE_ROOT
from .schema import SUBSCHEMA, SUBSCHEMA_LIST, SUBSCHEMA_MAP, check_schema, validate

GENERATED_NOTE = 'Generated by `wsc reg render` from `{src}`; do not edit. Change the rows with `wsc reg add|set` (or the JSONL) and re-render.'
STORAGES = ('jsonl', 'dir')
_DEVICE = re.compile(r'^(con|prn|aux|nul|com[1-9]|lpt[1-9])(\.|$)', re.I)


class RegistryError(Exception):
    pass


def id_to_file(rid):
    """The file name of a row in `dir` storage: the id percent-encoded (UTF-8; every character but ASCII letters, digits and `_.-~`
    becomes %XX, `%` itself included), its first character also encoded when the name would start with a Windows device name
    (CON, NUL, COM1 ...), then `.json`. Reversible (file_to_id) and Windows-safe by the `windows_paths` rule: no reserved character,
    no device name, no trailing dot or space. `J55` -> `J55.json`, `a.b c` -> `a.b%20c.json`, `con` -> `%63on.json`."""
    if not isinstance(rid, str) or not rid:
        raise RegistryError(f'id {rid!r}: a row stored one per file needs a non-empty string id')
    name = quote(rid, safe='')
    if _DEVICE.match(name):
        name = f'%{ord(name[0]):02X}' + name[1:]
    return name + '.json'


def file_to_id(fname):
    return unquote(fname[:-len('.json')] if fname.endswith('.json') else fname, errors='strict')


def schema_path(spec, root):
    if spec.startswith('core:'):
        return CORE_ROOT / 'schemas' / f'{spec[5:]}.schema.json'
    return Path(root) / spec


# x-extends: the keys an extending document may hold (anything else could change the core's meaning, so it is refused, not merged)
EXTENDS_KEYS = ('x-extends', '$schema', '$id', '$comment', 'title', 'description', 'properties', 'required', 'allOf', '$defs',
                'x-view', 'x-unique')
_EXTENDS_OWN = ('x-view', 'title', 'description', '$id')   # the game's value replaces the core's


def load_schema(spec, root):
    """The schema document of `spec` ("core:N" or a repo-relative path) with `x-extends` resolved: the merged document. Every reader of
    a schema file goes through this (`Registry`, the `schemas` gate); the caller runs `check_schema` on the result. Raises RegistryError."""
    doc = _read_schema(spec, root)
    _no_nested_extends(doc, '#', spec)
    if 'x-extends' not in doc:
        return doc
    if spec.startswith('core:'):
        raise RegistryError(f'{spec}: a core schema never extends another (x-extends)')
    target = doc['x-extends']
    if not isinstance(target, str) or not target.startswith('core:') or len(target) <= 5:
        raise RegistryError(f'{spec}: x-extends must be "core:<name>" (a core schema; a game schema cannot extend another game '
                            f'schema), not {target!r}')
    bad = [k for k in doc if k not in EXTENDS_KEYS]
    if bad:
        raise RegistryError(f'{spec}: {", ".join(repr(k) for k in bad)} cannot be set by a schema that extends {target} '
                            f'(allowed: {", ".join(EXTENDS_KEYS)}); narrow a core rule with an allOf entry instead')
    core = _read_schema(target, root)
    if 'x-extends' in core:
        raise RegistryError(f'{target}: a core schema never extends another (x-extends)')
    out = {k: v for k, v in core.items()}
    for key, kind in (('properties', dict), ('$defs', dict), ('required', list), ('allOf', list), ('x-unique', list)):
        if key in doc and not isinstance(doc[key], kind):
            raise RegistryError(f'{spec}: {key} must be a JSON {"object" if kind is dict else "array"}')
    for key in ('properties', '$defs'):
        if key not in doc:
            continue
        base = core.get(key, {})
        clash = [k for k in doc[key] if k in base]
        if clash:
            how = 'narrow a core property with an allOf entry instead' if key == 'properties' else 'rename the game\'s'
            raise RegistryError(f'{spec}: {key} {", ".join(repr(k) for k in clash)} already in {target} ({how})')
        out[key] = {**base, **doc[key]}
    if 'required' in doc:
        base = list(core.get('required', []))
        out['required'] = base + [k for k in doc['required'] if k not in base]
    for key in ('allOf', 'x-unique'):
        if key in doc:
            out[key] = list(core.get(key, [])) + list(doc[key])
    for key in _EXTENDS_OWN:
        if key in doc:
            out[key] = doc[key]
    return out


def _read_schema(spec, root):
    sp = schema_path(spec, root)
    try:
        doc = json.loads(sp.read_text(encoding='utf-8'))
    except (OSError, ValueError) as e:
        raise RegistryError(f'{spec}: cannot load schema {sp}: {e}') from None
    if not isinstance(doc, dict):
        raise RegistryError(f'{spec}: schema {sp} is not a JSON object')
    return doc


def _no_nested_extends(node, where, spec):
    """x-extends is read at the top level only: below it the validator skips `x-` keys, so it would be silently ignored."""
    if not isinstance(node, dict):
        return
    if where != '#' and 'x-extends' in node:
        raise RegistryError(f'{spec}: {where}/x-extends: x-extends is allowed only at the top level of a schema')
    for k, v in node.items():
        if k in SUBSCHEMA:
            _no_nested_extends(v, f'{where}/{k}', spec)
        elif k in SUBSCHEMA_MAP and isinstance(v, dict):
            for n, s in v.items():
                _no_nested_extends(s, f'{where}/{k}/{n}', spec)
        elif k in SUBSCHEMA_LIST and isinstance(v, list):
            for i, s in enumerate(v):
                _no_nested_extends(s, f'{where}/{k}/{i}', spec)


class Registry:
    def __init__(self, name, spec, root, reg_dir, label=None, storage='jsonl', views=None):
        """storage: 'jsonl' or 'dir'; views: the `[views]` table {commit, dir} (None: committed views)."""
        if storage not in STORAGES:
            raise RegistryError(f'{name}: unknown storage {storage!r} (one of {", ".join(STORAGES)})')
        self.name, self.spec, self.root, self.storage = name, spec, Path(root), storage
        self.label = label or name
        self.rel_path = f'{reg_dir}/{name}.jsonl' if storage == 'jsonl' else f'{reg_dir}/{name}'
        self.rel_other = f'{reg_dir}/{name}' if storage == 'jsonl' else f'{reg_dir}/{name}.jsonl'
        self.rel_committed_view = f'{reg_dir}/{name}.md'
        self.commit_view = True if views is None else views['commit']
        self.rel_view = self.rel_committed_view if self.commit_view else f'{views["dir"].rstrip("/")}/{name}.md'
        self.path = self.root / self.rel_path
        self.view_path = self.root / self.rel_view
        try:
            self.schema = load_schema(spec, root)
        except RegistryError as e:
            raise RegistryError(f'{name}: {e}') from None
        errs = check_schema(self.schema)
        if errs:
            raise RegistryError(f'{name}: schema {schema_path(spec, root)} is not usable:\n  ' + '\n  '.join(errs))
        self.props = list(self.schema.get('properties', {}))
        self.files = {}
        self.rows, self.parse_errors = self._load()

    # ------------------------------------------------------------------ io
    def _load(self):
        if self.storage == 'dir':
            return self._load_dir()
        rows, errs = [], []
        self.missing = not self.path.exists()
        if self.missing:
            return rows, errs
        for i, line in enumerate(self.path.read_text(encoding='utf-8').split('\n'), 1):
            if not line.strip():
                continue
            try:
                r = json.loads(line, parse_constant=_boom)
            except ValueError as e:
                errs.append(f'{self.rel_path}:{i}: not strict JSON: {e}')
                continue
            if not isinstance(r, dict):
                errs.append(f'{self.rel_path}:{i}: a row must be a JSON object')
                continue
            rows.append(r)
        return rows, errs

    def _load_dir(self):
        """Rows from N/*.json; a missing folder is an empty registry (git keeps no empty folder). Fills self.files {name: text}."""
        rows, errs, self.missing = [], [], False
        if not self.path.is_dir():
            return rows, errs
        for f in sorted(self.path.iterdir(), key=lambda f: f.name):
            rel = f'{self.rel_path}/{f.name}'
            if not f.is_file() or not f.name.endswith('.json'):
                errs.append(f'{rel}: only <id>.json row files belong in {self.rel_path}/ (move or delete it)')
                continue
            text = f.read_text(encoding='utf-8')
            self.files[f.name] = text
            try:
                r = json.loads(text, parse_constant=_boom)
            except ValueError as e:
                errs.append(f'{rel}: not strict JSON: {e}')
                continue
            if not isinstance(r, dict):
                errs.append(f'{rel}: a row must be a JSON object')
                continue
            try:
                want = id_to_file(r.get('id'))
            except RegistryError as e:
                want = None
                errs.append(f'{rel}: {e}')
            if want and want != f.name:
                errs.append(f'{rel}: holds id {r.get("id")!r}, whose file is {want} (rename the file, or fix the id)')
            rows.append(r)
        return rows, errs

    def order(self, row):
        keys = [k for k in self.props if k in row] + sorted(k for k in row if k not in self.props)
        return {k: row[k] for k in keys}

    def canonical(self, rows=None):
        """jsonl storage: the whole file's text (dir storage: canonical_files)."""
        rows = self.rows if rows is None else rows
        lines = [json.dumps(self.order(r), ensure_ascii=False, allow_nan=False) for r in sorted(rows, key=lambda r: str(r.get('id', '')))]
        return ''.join(l + '\n' for l in lines)

    def canonical_row(self, row):
        return json.dumps(self.order(row), ensure_ascii=False, allow_nan=False, indent=2) + '\n'

    def canonical_files(self, rows=None):
        """dir storage: {file name: text} for the rows."""
        return {id_to_file(r.get('id')): self.canonical_row(r) for r in (self.rows if rows is None else rows)}

    def save(self):
        """Write the rows in canonical form. dir storage rewrites only the files whose text changes and deletes row files with no row."""
        if self.storage == 'jsonl':
            self.path.parent.mkdir(parents=True, exist_ok=True)
            _write(self.path, self.canonical())
            return
        want = self.canonical_files()
        if not want:                   # an empty registry is no folder (git keeps none)
            self.remove_storage()
            self.files = {}
            return
        self.path.mkdir(parents=True, exist_ok=True)
        for f in self.path.glob('*.json'):
            if f.name not in want:
                f.unlink()
        for name, text in want.items():
            f = self.path / name
            if not f.is_file() or f.read_text(encoding='utf-8') != text:
                _write(f, text)
        self.files = want

    def remove_storage(self):
        """Delete this registry's rows from disk (`reg migrate`, after the other storage is written)."""
        if self.storage == 'jsonl':
            self.path.unlink(missing_ok=True)
        elif self.path.is_dir():
            for f in self.path.glob('*.json'):
                f.unlink()
            if not any(self.path.iterdir()):
                self.path.rmdir()

    def by_id(self):
        return {r.get('id'): r for r in self.rows}

    # ------------------------------------------------------------------ rows
    def validate_row(self, row):
        return validate(row, self.schema)

    def add(self, row, replace=False):
        errs = self.validate_row(row)
        if errs:
            raise RegistryError(f'{self.name}: row {row.get("id")!r} is not valid:\n  ' + '\n  '.join(errs))
        ids = self.by_id()
        if row['id'] in ids and not replace:
            raise RegistryError(f'{self.name}: id {row["id"]!r} already exists (use `wsc reg set {self.name} {row["id"]} field=value`)')
        if self.storage == 'dir':
            key = id_to_file(row['id']).casefold()
            clash = [i for i in ids if i != row['id'] and isinstance(i, str) and i and id_to_file(i).casefold() == key]
            if clash:
                raise RegistryError(f'{self.name}: id {row["id"]!r} differs from {clash[0]!r} only in case: on Windows they would be one file')
        self.rows = [r for r in self.rows if r.get('id') != row['id']] + [row]

    def set(self, rid, changes):
        ids = self.by_id()
        if rid not in ids:
            raise RegistryError(f'{self.name}: no row with id {rid!r}')
        row = dict(ids[rid])
        for k, v in changes.items():
            if k == 'id':
                raise RegistryError('the id of a row cannot be changed with set (add a new row and supersede or remove the old one)')
            if v is None:
                row.pop(k, None)
            else:
                row[k] = v
        self.add(row, replace=True)
        return row

    def remove(self, ids):
        """Drop the rows with these ids in memory and return them (in the order given); `save()` writes the change (in `dir` storage
        it deletes their files). An unknown id raises RegistryError naming the registry, and nothing is dropped. `wsc reg remove`
        checks first that nothing points at them."""
        have = self.by_id()
        bad = [i for i in ids if i not in have]
        if bad:
            raise RegistryError('; '.join(f'{self.name}: no row with id {i!r}' for i in bad))
        gone = set(ids)
        self.rows = [r for r in self.rows if r.get('id') not in gone]
        return [have[i] for i in dict.fromkeys(ids)]

    def row_file(self, rid):
        """The repo-relative file that holds row `rid` (its own file in `dir` storage, else the JSONL)."""
        if self.storage == 'dir':
            try:
                return f'{self.rel_path}/{id_to_file(rid)}'
            except RegistryError:
                pass
        return self.rel_path

    def refs_to(self, target, ids):
        """[(row id, field, value)] for each value of an `x-ref: <target>` property (directly or on `items`) that is in `ids`."""
        out = []
        for field, ps in self.schema.get('properties', {}).items():
            if not isinstance(ps, dict) or (ps.get('x-ref') or (ps.get('items') or {}).get('x-ref')) != target:
                continue
            for r in self.rows:
                v = r.get(field)
                for x in (v if isinstance(v, list) else [v] if v is not None else []):
                    if x in ids:
                        out.append((r.get('id'), field, x))
        return out

    # ------------------------------------------------------------------ view
    def render(self):
        view = self.schema.get('x-view', {})
        cols = view.get('columns') or ['id', 'description']
        title = view.get('title') or self.schema.get('title') or self.name
        src = self.rel_path + ('/' if self.storage == 'dir' else '')
        out = [f'# {title}', '', GENERATED_NOTE.format(src=src), '']
        if self.schema.get('description'):
            out += [self.schema['description'], '']
        out += [f'{len(self.rows)} rows. Search every registry: `wsc find <words>`.', '']
        if self.rows:
            out += ['| ' + ' | '.join(cols) + ' |', '|' + '---|' * len(cols)]
            for r in sorted(self.rows, key=lambda r: str(r.get('id', ''))):
                out.append('| ' + ' | '.join(_cell(r.get(c), code=(c in ('id', 'path', 'usage'))) for c in cols) + ' |')
            out.append('')
        return '\n'.join(out)

    def view_stale(self):
        try:
            return self.view_path.read_text(encoding='utf-8') != self.render()
        except OSError:
            return True

    def write_view(self, out_dir=None):
        """Write the view (to out_dir/N.md when given, else to its configured place); returns the path written."""
        p = Path(out_dir) / f'{self.name}.md' if out_dir else self.view_path
        p.parent.mkdir(parents=True, exist_ok=True)
        _write(p, self.render())
        return p

    # ------------------------------------------------------------------ check
    def check(self, all_regs):
        """Errors for this registry alone and its cross-registry refs; the tools coverage check lives in warscape.tools."""
        errs = list(self.parse_errors)
        if self.missing:
            return errs + [f'{self.rel_path}: missing: run `wsc reg render {self.name}` (creates it empty)']
        if (self.root / self.rel_other).exists():
            errs.append(f'{self.rel_other}: a second copy of {self.name}, in the storage this repo does not declare for it (it is '
                        f'{self.storage}: `[storage] dir`): delete the stale copy (`wsc reg migrate` leaves only one)')
        if self.storage == 'jsonl':
            if not errs and self.path.read_text(encoding='utf-8') != self.canonical():
                errs.append(f'{self.rel_path}: not in canonical form (rows sorted by id, keys in schema order): run `wsc reg render {self.name}`')
        else:
            for r in self.rows:
                try:
                    name = id_to_file(r.get('id'))
                except RegistryError:
                    continue
                if name in self.files and self.files[name] != self.canonical_row(r):
                    errs.append(f'{self.rel_path}/{name}: not in canonical form (keys in schema order, indented 2): run `wsc reg render {self.name}`')
        seen = {}
        for r in self.rows:
            rid = r.get('id')
            if rid in seen:
                errs.append(f'{self.rel_path}: duplicate id {rid!r} (a merge kept two versions of a row: keep one)')
            seen[rid] = r
            errs += [f'{self.rel_path}: {rid}: {e}' for e in self.validate_row(r)]
        errs += self._check_unique()
        errs += self._check_refs(all_regs)
        if self.commit_view:
            if self.view_stale():
                errs.append(f'{self.rel_view}: stale or missing: run `wsc reg render {self.name}`')
        else:
            if (self.root / self.rel_committed_view).exists():
                errs.append(f'{self.rel_committed_view}: views are not committed in this repo (`[views] commit = false`): delete it; '
                            f'`wsc reg render` writes {self.rel_view}')
            try:
                self.render()
            except Exception as e:   # the view is not compared with a file, but it must still render
                errs.append(f'{self.name}: the view does not render: {type(e).__name__}: {e}')
        return errs

    def _check_unique(self):
        errs = []
        wild = self.schema.get('x-wildcard', {})
        chord = self.schema.get('x-chord') or {}
        for fields in self.schema.get('x-unique', []):
            seen = []
            for r in self.rows:
                if not all(f in r for f in fields):
                    continue
                key = [str(r[f]).casefold() for f in fields]
                for other, okey in seen:
                    how = []
                    if all(_same(f, a, b, wild) or (f == chord.get('field') and _chord_reach(r, other, chord, how))
                           for f, a, b in zip(fields, key, okey)):
                        errs.append(f'{self.rel_path}: clash on ({", ".join(fields)}) between {other.get("id")!r} and {r.get("id")!r}: '
                                    + ', '.join(f'{f}={r[f]!r}' for f in fields) + (f': {how[0]}' if how else ''))
                seen.append((r, key))
        return errs

    def _check_refs(self, all_regs):
        errs = []
        for field, ps in self.schema.get('properties', {}).items():
            target = ps.get('x-ref') or (ps.get('items') or {}).get('x-ref') if isinstance(ps, dict) else None
            if not target:
                continue
            # An undeclared target only matters once a row fills the field: a game may use `assets` without `ui_elements`.
            ids = set(all_regs[target].by_id()) if target in all_regs else None
            for r in self.rows:
                v = r.get(field)
                for x in (v if isinstance(v, list) else [v] if v is not None else []):
                    if ids is None:
                        errs.append(f'{self.rel_path}: {r.get("id")}: {field} {x!r} points at registry {target!r}, which this repo '
                                    f'does not declare (declare it in wsc.toml, or leave the field empty)')
                        break
                    if x not in ids:
                        errs.append(f'{self.rel_path}: {r.get("id")}: {field} {x!r} is not an id in {target}')
        return errs


def _same(f, a, b, wild):
    """x-unique: two casefolded values match when equal, or when either is the field's x-wildcard value."""
    return a == b or (f in wild and str(wild[f]).casefold() in (a, b))


CHORD_FLAGS = {'any_modifier': 'fires with any modifier', 'shift': 'fires alone or with Shift'}


def _chord_reach(r, o, chord, how):
    """x-chord: does a flagged bare key in one of rows r, o also fire for the other's chord? Appends the reason to `how`."""
    f, flag = chord['field'], chord.get('flag')
    for w, x in ((r, o), (o, r)):
        fw = w.get(flag)
        if fw not in CHORD_FLAGS:
            continue
        wmods, wkey = _split_chord(w[f])
        xmods, xkey = _split_chord(x[f])
        if wmods or wkey != xkey:
            continue
        if fw == 'any_modifier' or xmods in ([], ['shift']):
            how.append(f'{x[f]} reaches {w[f]}, which {CHORD_FLAGS[fw]}')
            return True
    return False


def _split_chord(v):
    """`Ctrl+Shift+Space` -> (['ctrl', 'shift'], 'space'), casefolded."""
    parts = str(v).casefold().split('+')
    return parts[:-1], parts[-1]


