"""The registry framework: every registry is a JSONL file + a JSON Schema + a generated Markdown view + a check.

Files, for a registry named N declared in `wsc.toml` `[registries]`:
  <registries_dir>/N.jsonl   one row per line, canonical form (rows sorted by id, keys in schema order); the source of truth
  <registries_dir>/N.md      generated view; never edit it, run `wsc reg render`
Schema: "core:N" means the core's `schemas/N.schema.json`; anything else is a repo-relative path.

Registry extensions in the schema (ignored by the validator):
  x-view:   {"title": str, "columns": [field, ...]}            columns of the generated table (default: id, description)
  x-unique: [[field, ...], ...]                                 field tuples that must be unique across rows (compared case-insensitively)
  x-wildcard: {field: value}                                   a row with this value in an x-unique field clashes with every value
  x-ref:    on a property: "<registry>"                         the value (or each item of an array) must be an id in that registry
  x-source: "tool-headers"                                      rows are derived from file headers (warscape.tools adds the coverage check)
"""
import json
from pathlib import Path

from . import CORE_ROOT
from .schema import check_schema, validate

GENERATED_NOTE = 'Generated by `wsc reg render` from `{src}`; do not edit. Change the rows with `wsc reg add|set` (or the JSONL) and re-render.'


class RegistryError(Exception):
    pass


def schema_path(spec, root):
    if spec.startswith('core:'):
        return CORE_ROOT / 'schemas' / f'{spec[5:]}.schema.json'
    return Path(root) / spec


class Registry:
    def __init__(self, name, spec, root, reg_dir, label=None):
        self.name, self.spec, self.root = name, spec, Path(root)
        self.label = label or name
        self.rel_path = f'{reg_dir}/{name}.jsonl'
        self.rel_view = f'{reg_dir}/{name}.md'
        self.path = self.root / self.rel_path
        self.view_path = self.root / self.rel_view
        sp = schema_path(spec, root)
        try:
            self.schema = json.loads(sp.read_text(encoding='utf-8'))
        except (OSError, json.JSONDecodeError) as e:
            raise RegistryError(f'{name}: cannot load schema {sp}: {e}') from None
        errs = check_schema(self.schema)
        if errs:
            raise RegistryError(f'{name}: schema {sp} is not usable:\n  ' + '\n  '.join(errs))
        self.props = list(self.schema.get('properties', {}))
        self.rows, self.parse_errors = self._load()

    # ------------------------------------------------------------------ io
    def _load(self):
        rows, errs = [], []
        self.missing = not self.path.exists()
        if self.missing:
            return rows, errs
        def boom(c):
            raise ValueError(f'non-finite number {c}')
        for i, line in enumerate(self.path.read_text(encoding='utf-8').split('\n'), 1):
            if not line.strip():
                continue
            try:
                r = json.loads(line, parse_constant=boom)
            except ValueError as e:
                errs.append(f'{self.rel_path}:{i}: not strict JSON: {e}')
                continue
            if not isinstance(r, dict):
                errs.append(f'{self.rel_path}:{i}: a row must be a JSON object')
                continue
            rows.append(r)
        return rows, errs

    def order(self, row):
        keys = [k for k in self.props if k in row] + sorted(k for k in row if k not in self.props)
        return {k: row[k] for k in keys}

    def canonical(self, rows=None):
        rows = self.rows if rows is None else rows
        lines = [json.dumps(self.order(r), ensure_ascii=False, allow_nan=False) for r in sorted(rows, key=lambda r: str(r.get('id', '')))]
        return ''.join(l + '\n' for l in lines)

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with open(self.path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(self.canonical())

    def by_id(self):
        return {r.get('id'): r for r in self.rows}

    # ------------------------------------------------------------------ rows
    def validate_row(self, row):
        return validate(row, self.schema)

    def add(self, row, replace=False):
        errs = self.validate_row(row)
        if errs:
            raise RegistryError(f'{self.name}: row {row.get("id")!r} is not valid:\n  ' + '\n  '.join(errs))
        ids = self.by_id()
        if row['id'] in ids and not replace:
            raise RegistryError(f'{self.name}: id {row["id"]!r} already exists (use `wsc reg set {self.name} {row["id"]} field=value`)')
        self.rows = [r for r in self.rows if r.get('id') != row['id']] + [row]

    def set(self, rid, changes):
        ids = self.by_id()
        if rid not in ids:
            raise RegistryError(f'{self.name}: no row with id {rid!r}')
        row = dict(ids[rid])
        for k, v in changes.items():
            if k == 'id':
                raise RegistryError('the id of a row cannot be changed with set (add a new row and supersede or remove the old one)')
            if v is None:
                row.pop(k, None)
            else:
                row[k] = v
        self.add(row, replace=True)
        return row

    # ------------------------------------------------------------------ view
    def render(self):
        view = self.schema.get('x-view', {})
        cols = view.get('columns') or ['id', 'description']
        title = view.get('title') or self.schema.get('title') or self.name
        out = [f'# {title}', '', GENERATED_NOTE.format(src=self.rel_path), '']
        if self.schema.get('description'):
            out += [self.schema['description'], '']
        out += [f'{len(self.rows)} rows. Search every registry: `wsc find <words>`.', '']
        if self.rows:
            out += ['| ' + ' | '.join(cols) + ' |', '|' + '---|' * len(cols)]
            for r in sorted(self.rows, key=lambda r: str(r.get('id', ''))):
                out.append('| ' + ' | '.join(_cell(r.get(c), code=(c in ('id', 'path', 'usage'))) for c in cols) + ' |')
            out.append('')
        return '\n'.join(out)

    def view_stale(self):
        try:
            return self.view_path.read_text(encoding='utf-8') != self.render()
        except OSError:
            return True

    def write_view(self):
        with open(self.view_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(self.render())

    # ------------------------------------------------------------------ check
    def check(self, all_regs):
        """Errors for this registry alone and its cross-registry refs; the tools coverage check lives in warscape.tools."""
        errs = list(self.parse_errors)
        if self.missing:
            return errs + [f'{self.rel_path}: missing: run `wsc reg render {self.name}` (creates it empty)']
        if not errs and self.path.read_text(encoding='utf-8') != self.canonical():
            errs.append(f'{self.rel_path}: not in canonical form (rows sorted by id, keys in schema order): run `wsc reg render {self.name}`')
        seen = {}
        for r in self.rows:
            rid = r.get('id')
            if rid in seen:
                errs.append(f'{self.rel_path}: duplicate id {rid!r} (a merge kept two versions of a row: keep one)')
            seen[rid] = r
            errs += [f'{self.rel_path}: {rid}: {e}' for e in self.validate_row(r)]
        errs += self._check_unique()
        errs += self._check_refs(all_regs)
        if self.view_stale():
            errs.append(f'{self.rel_view}: stale or missing: run `wsc reg render {self.name}`')
        return errs

    def _check_unique(self):
        errs = []
        wild = self.schema.get('x-wildcard', {})
        for fields in self.schema.get('x-unique', []):
            seen = []
            for r in self.rows:
                if not all(f in r for f in fields):
                    continue
                key = [str(r[f]).casefold() for f in fields]
                for other, okey in seen:
                    if all(a == b or (f in wild and str(wild[f]).casefold() in (a, b)) for f, a, b in zip(fields, key, okey)):
                        errs.append(f'{self.rel_path}: clash on ({", ".join(fields)}) between {other!r} and {r.get("id")!r}: '
                                    + ', '.join(f'{f}={r[f]!r}' for f in fields))
                seen.append((r.get('id'), key))
        return errs

    def _check_refs(self, all_regs):
        errs = []
        for field, ps in self.schema.get('properties', {}).items():
            target = ps.get('x-ref') or (ps.get('items') or {}).get('x-ref') if isinstance(ps, dict) else None
            if not target:
                continue
            # An undeclared target only matters once a row fills the field: a game may use `assets` without `ui_elements`.
            ids = set(all_regs[target].by_id()) if target in all_regs else None
            for r in self.rows:
                v = r.get(field)
                for x in (v if isinstance(v, list) else [v] if v is not None else []):
                    if ids is None:
                        errs.append(f'{self.rel_path}: {r.get("id")}: {field} {x!r} points at registry {target!r}, which this repo '
                                    f'does not declare (declare it in wsc.toml, or leave the field empty)')
                        break
                    if x not in ids:
                        errs.append(f'{self.rel_path}: {r.get("id")}: {field} {x!r} is not an id in {target}')
        return errs


def _cell(v, code=False):
    if v is None or v == '' or v == []:
        return ''
    if isinstance(v, list):
        s = ', '.join(x if isinstance(x, str) else json.dumps(x, ensure_ascii=False) for x in v)
    elif isinstance(v, dict):
        s = json.dumps(v, ensure_ascii=False)
    elif isinstance(v, bool):
        s = 'yes' if v else 'no'
    else:
        s = str(v)
    s = ' '.join(s.split()).replace('|', '\\|')
    if len(s) > 200:
        s = s[:197] + '...'
    return f'`{s}`' if code and '`' not in s else s


def load_all(ctx):
    """{name: Registry} for every registry the repo declares (raises RegistryError on an unusable schema)."""
    d = ctx.config['registries_dir']
    return {n: Registry(n, spec, ctx.root, d) for n, spec in ctx.config['registries'].items()}


def core_tools(ctx):
    """The core's own tools registry when running in a game repo (so `find` sees the core's verbs too); None inside the core."""
    if ctx.is_core:
        return None
    from .repo import load_config
    try:
        cfg = load_config(ctx.core_root)
        spec = cfg['registries'].get('tools')
        return Registry('tools', spec, ctx.core_root, cfg['registries_dir'], label='core:tools') if spec else None
    except Exception:
        return None
