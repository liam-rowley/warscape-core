"""Workflow templates: `wsc ci render` writes a repo's GitHub workflows from `<template dir>/<name>.in`, filling the generic jobs from `[ci]`.

Why templates and not a reusable (`workflow_call`) workflow: a called workflow reports its checks as `<caller job> / <called job>`, which renames
the checks branch protection and auto-merge wait for; a rendered file keeps the job ids and names (`changes`, `gates`, `policy`, `notify`, ...),
and the `ci_render` gate fails when a committed workflow differs from its render (napoleon J62).

A template is the workflow file with placeholder lines `{{wsc <block> [args]}}` (the line may be indented; it is replaced whole by the block's
text, which carries its own indentation). Blocks:
  changes                      the `changes` job: input sets from [ci] inputs, the pass-marker restore steps, the decision per set
  if <set> [dispatch]          the `if:` line of a slow job: runs whenever `changes` failed, else when the set changed and has no pass marker
                               (`dispatch`: also on every workflow_dispatch run)
  pass_marker <set> [shell=S]  the last two steps of a slow job: write and save the pass marker for the set's input tree
  policy                       the `policy` job (pull requests; skips drafts); [ci] policy_extra_steps are inserted before the command
  notify gates needs=a,b,c     the failure-comment job of a push workflow, after the jobs a, b, c
  notify policy                the failure-comment job of the policy workflow
The first line of a rendered file says it is generated. Slow job bodies stay in the template, outside the blocks.
"""
from pathlib import Path

GENERATED = '# Generated by `wsc ci render` from {src}: do not edit this file; edit the template or [ci] in wsc.toml.'
REF_CHECKOUT = 'actions/checkout@v5'


def _wsc(cfg):
    return 'python3 core/wsc.py' if cfg['core'] else 'python3 wsc.py'


def _token(cfg, indent):
    return f"\n{indent}token: ${{{{ secrets.{cfg['token_secret']} }}}}" if cfg['token_secret'] else ''


def block_changes(cfg):
    sets = list(cfg['inputs'])
    wsc = _wsc(cfg)
    out = ['  # changes: which slow jobs this run needs. Diffs against the merge base with main (a push to any branch but main)',
           '  # or the previous main tip (a push to main). When the base is unknown (first push to main, a force push past it) everything runs.',
           f'  # Which files feed which job: `wsc.toml` [ci] inputs, read by `{wsc} ci inputs`. Then a changed set whose tree hash has a pass marker',
           '  # is turned off; its outputs are the combined answer: true = inputs changed against the base AND no marker for this tree.',
           '  changes:', '    runs-on: ubuntu-latest', '    timeout-minutes: 5', '    outputs:']
    out += [f'      {k}: ${{{{ steps.run.outputs.{k} }}}}' for k in sets]
    out += [f'      {k}_tree: ${{{{ steps.diff.outputs.{k}_tree }}}}' for k in sets]
    out += ['      tree_salt: ${{ steps.diff.outputs.tree_salt }}', '    steps:', f'      - uses: {REF_CHECKOUT}', '        with:',
            '          fetch-depth: 0' + _token(cfg, '          ')]
    if cfg['core']:
        out += [f"      # only the {cfg['core']} commit this repo pins, shallow: the verbs need no history", f"      - run: git submodule update --init --depth 1 {cfg['core']}"]
    out += ['      - id: diff', '        env:', '          BEFORE: ${{ github.event.before }}', '        run: |',
            '          if [ "$GITHUB_REF" = refs/heads/main ]; then base=$BEFORE', '          else base=$(git merge-base origin/main HEAD || true); fi',
            f'          {wsc} ci inputs --base "$base" >> "$GITHUB_OUTPUT"', '          cat "$GITHUB_OUTPUT"',
            '      # pass markers: looked up only for a set that changed, on a push, with a hash; the marker is a one-line file, restored whole']
    for k in sets:
        out += [f'      - id: {k}_pass',
                f"        if: github.event_name == 'push' && steps.diff.outputs.{k} == 'true' && steps.diff.outputs.{k}_tree != ''",
                '        continue-on-error: true', '        uses: actions/cache/restore@v5', '        with:', f'          path: .ci-pass/{k}',
                f'          key: ci-pass-${{{{ steps.diff.outputs.tree_salt }}}}-{k}-${{{{ steps.diff.outputs.{k}_tree }}}}',
                '          enableCrossOsArchive: true']
    out += ['      # a set runs when its inputs changed and no readable marker exists for its tree hash; a skip names the run that passed it',
            '      - id: run', '        env:']
    out += [f'          {k.upper()}: ${{{{ steps.diff.outputs.{k} }}}}' for k in sets]
    out += [f'          {k.upper()}_HIT: ${{{{ steps.{k}_pass.outputs.cache-hit }}}}' for k in sets]
    out += ['        run: |', '          decide() {   # set, changed, cache-hit, artifact', '            m=.ci-pass/$1/marker.txt',
            '            if [ "$2" = true ] && [ "$3" = true ] && grep -q \'^run=[0-9]\' "$m" 2>/dev/null; then',
            '              echo "$1=false" >> "$GITHUB_OUTPUT"',
            "              run=$(sed -n 's/^run=//p' \"$m\"); attempt=$(sed -n 's/^attempt=//p' \"$m\"); commit=$(sed -n 's/^commit=//p' \"$m\")",
            "              tree=$(sed -n 's/^tree=//p' \"$m\")",
            '              line="\\`$1\\` skipped: its input tree $tree already passed in run $run (attempt $attempt, commit $commit)"',
            '              [ -n "$4" ] && line="$line; its build: \\`gh run download $run -n $4\\`"',
            '              echo "- $line" >> "$GITHUB_STEP_SUMMARY"; echo "$line"', '            else', '              echo "$1=$2" >> "$GITHUB_OUTPUT"',
            '            fi', '          }']
    out += [f"          decide {k} \"${k.upper()}\" \"${k.upper()}_HIT\" {cfg['artifacts'].get(k) or chr(39) * 2}" for k in sets]
    out += ['          cat "$GITHUB_OUTPUT"']
    return '\n'.join(out)


def block_if(cfg, name, dispatch=False):
    core = f"needs.changes.result != 'success' || needs.changes.outputs.{name} == 'true'"
    if dispatch:
        return f"    if: ${{{{ !cancelled() && (github.event_name == 'workflow_dispatch' || {core}) }}}}"
    return f"    if: ${{{{ !cancelled() && github.event_name != 'workflow_dispatch' && ({core}) }}}}"


def block_pass_marker(cfg, name, shell=''):
    t = f"needs.changes.outputs.{name}_tree != ''"
    out = ['      # pass marker: the last step, on success of a push run only; `changes` skips this job on the same input tree',
           '      - name: pass marker', f"        if: success() && github.event_name == 'push' && {t}"]
    if shell:
        out.append(f'        shell: {shell}')
    out += ['        env:', f'          TREE: ${{{{ needs.changes.outputs.{name}_tree }}}}', '        run: |', f'          mkdir -p .ci-pass/{name}',
            f'          {{ echo "set={name}"; echo "tree=$TREE"; echo "run=$GITHUB_RUN_ID"; echo "attempt=$GITHUB_RUN_ATTEMPT"; '
            f'echo "commit=$GITHUB_SHA"; }} > .ci-pass/{name}/marker.txt',
            f'          cat .ci-pass/{name}/marker.txt', f"      - if: success() && github.event_name == 'push' && {t}", '        uses: actions/cache/save@v5',
            '        with:', f'          path: .ci-pass/{name}',
            f'          key: ci-pass-${{{{ needs.changes.outputs.tree_salt }}}}-{name}-${{{{ needs.changes.outputs.{name}_tree }}}}',
            '          enableCrossOsArchive: true']
    return '\n'.join(out)


def block_policy(cfg):
    wsc = _wsc(cfg).replace('python3', 'python')
    out = ['  policy:', '    # Every pull request must be a reviewed job, a brief, a planning change or an infrastructure change (`wsc policy`).',
           '    if: github.event.pull_request.draft == false', '    runs-on: ubuntu-latest', '    timeout-minutes: 5', '    steps:',
           f'      - uses: {REF_CHECKOUT}', '        with:', '          fetch-depth: 0' + (f"\n          submodules: true{_token(cfg, '          ')}" if cfg['core'] else ''),
           "      - uses: actions/setup-python@v6", "        with:", "          python-version: '3.12'"]
    extra = cfg.get('policy_extra_steps', '').rstrip('\n')
    if extra:
        out.append(extra)
    out.append(f'      - run: {wsc} policy --branch "${{{{ github.head_ref }}}}" --base "origin/${{{{ github.base_ref }}}}"')
    return '\n'.join(out)


def block_notify(cfg, kind, needs=''):
    wsc = _wsc(cfg)
    if kind == 'policy':
        head = ['  notify:', '    needs: [policy]', "    if: failure() && github.event.action != 'ready_for_review'"]
        branch = '${{ github.head_ref }}'
    else:
        head = ['  notify:', f'    needs: [{", ".join(needs.split(","))}]',
                "    if: failure() && github.event_name == 'push' && github.ref != 'refs/heads/main'"]
        branch = '${{ github.ref_name }}'
    out = head + ['    runs-on: ubuntu-latest', '    timeout-minutes: 5', '    permissions:', '      contents: read', '      pull-requests: write', '      actions: read',
                  '    steps:', f'      - uses: {REF_CHECKOUT}']
    if cfg['core']:
        out += ['        with:', '          submodules: true' + _token(cfg, '          ')]
    out += ['      - env:', '          GH_TOKEN: ${{ github.token }}',
            f'        run: {wsc} ci notify --run-id ${{{{ github.run_id }}}} --attempt ${{{{ github.run_attempt }}}} --branch "{branch}" '
            '--repo "${{ github.repository }}"']
    return '\n'.join(out)


def expand(line, cfg):
    """The block text for one placeholder line, or None when `line` is not a placeholder."""
    s = line.strip()
    if not (s.startswith('{{wsc ') and s.endswith('}}')):
        return None
    words = s[6:-2].split()
    kw = dict(w.split('=', 1) for w in words[1:] if '=' in w)
    pos = [w for w in words[1:] if '=' not in w]
    name = words[0]
    if name == 'changes':
        return block_changes(cfg)
    if name == 'if':
        return block_if(cfg, pos[0], 'dispatch' in pos[1:])
    if name == 'pass_marker':
        return block_pass_marker(cfg, pos[0], kw.get('shell', ''))
    if name == 'policy':
        return block_policy(cfg)
    if name == 'notify':
        return block_notify(cfg, pos[0], kw.get('needs', ''))
    raise ValueError(f'unknown template block: {s}')


def render_text(template, cfg, src):
    out = [GENERATED.format(src=src)]
    for line in template.splitlines():
        got = expand(line, cfg)
        out.append(line if got is None else got)
    return '\n'.join(out) + '\n'


def targets(ctx):
    """[(template path, workflow path)] for every `[ci] workflows` name."""
    cfg = ctx.config['ci']
    return [(f"{cfg['template_dir']}/{n}.in", f'.github/workflows/{n}') for n in cfg['workflows']]


def problems(ctx):
    """What differs between each committed workflow and its render (the `ci_render` gate)."""
    errs = []
    for src, dst in targets(ctx):
        t = ctx.root / src
        if not t.is_file():
            errs.append(f'{src} is missing (listed in wsc.toml [ci] workflows)')
            continue
        want = render_text(t.read_text(encoding='utf-8'), ctx.config['ci'], src)
        f = ctx.root / dst
        have = f.read_text(encoding='utf-8') if f.is_file() else None
        if have != want:
            errs.append(f'{dst} differs from its render of {src}: run `wsc ci render`')
    return errs


def run(ctx, check=False):
    if not check:
        errs = []
    else:
        errs = problems(ctx)
    if check:
        for e in errs:
            print(f'ci render: {e}')
        print(f'ci render --check: {"ok" if not errs else "%d workflow(s) differ" % len(errs)}')
        return 1 if errs else 0
    for src, dst in targets(ctx):
        t = ctx.root / src
        text = render_text(t.read_text(encoding='utf-8'), ctx.config['ci'], src)
        f = ctx.root / dst
        f.parent.mkdir(parents=True, exist_ok=True)
        changed = not f.is_file() or f.read_text(encoding='utf-8') != text
        if changed:
            f.write_text(text, encoding='utf-8', newline='\n')
        print(f'ci render: {dst} {"written" if changed else "unchanged"} from {src}')
    return 0
