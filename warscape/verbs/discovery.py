"""
Purpose: Check every committed discovery result, render the generated discovery READMEs, run the discovery gate and (on the PC) the discovery passes; the game comes from `[discovery] adapter` in wsc.toml.
Usage: wsc discovery check | render | gate [--install] [--write] [--json OUT] | assets | sheets | db | loc | ui | all   (the passes read the install on the PC; all = assets, db, loc, sheets, ui, then render)
When: after any discovery pass (discovery/*.py) rewrites a result; `check` includes the gate and also fails when a committed README is stale; `gate --install` on the PC after a game update; `gate --write` rewrites discovery/gate/summary.json.
Verb: discovery
"""
import json
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from .. import CORE_ROOT

NAME = 'discovery'
HELP = 'discovery passes: check and render the committed results and the gate; run the passes on the PC'

AREAS = ('packs', 'layouts', 'fonts', 'lua_api', 'shaders', 'exe')
CELL = 90
PASSES = {'assets': 'assets.py', 'db': 'db.py', 'loc': 'loc.py', 'sheets': 'sheets.py', 'ui': 'ui_atlas.py'}
ORDER = ('assets', 'db', 'loc', 'sheets', 'ui')
DISCOVERY = CORE_ROOT / 'discovery'


def _core(root):
    """Put the discovery modules on the path and point their `paths` at this repo's game and adapter."""
    p = str(DISCOVERY)
    if p not in sys.path:
        sys.path.insert(0, p)
    import paths
    paths.configure(root)
    return paths


def _load(root):
    _core(root)
    from diffout import problems  # noqa: E402
    docs, bad = {}, []
    for a in AREAS:
        p = Path(root) / 'discovery' / 'diff' / f'{a}.json'
        if not p.exists():
            bad.append(f'{p}: missing')
            continue
        d = json.loads(p.read_text(encoding='utf-8'))
        bad += [f'{p}: {x}' for x in problems(d)]
        docs[a] = d
    return docs, bad


def _cell(v):
    s = str(v).replace('|', '/').replace('\n', ' ')
    return s if len(s) <= CELL else s[:CELL - 1] + '…'


def render(root):
    paths = _core(root)
    docs, bad = _load(root)
    if bad:
        raise ValueError('; '.join(bad))
    ref, tgt = paths.titled(paths.REFERENCE), paths.titled(paths.TARGET)
    co = json.loads((Path(paths.ADAPTER) / 'carry_over.json').read_text(encoding='utf-8'))
    out = [f'# {ref} to {tgt} diff (J6)', '',
           'Generated by `python3 core/wsc.py discovery render` from `discovery/diff/<area>.json` (written by `discovery/core/<area>.py`)',
           f'and `{paths.adapter_rel()}/carry_over.json`. Do not edit. Inputs and re-run steps: `discovery/README.md`.', '',
           f'## Carry-over of {ref} tools', '', '| Tool family | Verdict | Note |', '|---|---|---|']
    out += [f"| {_cell(f['family'])} | {f['verdict']} | {_cell(f['note'])} |" for f in co['families']]
    out += ['', '## Rows', '', 'Every row whose verdict is not `same`; the `same` rows are counted per area. Full rows and detail: the area file.', '',
            '| Area | Same rows |', '|---|---|']
    out += [f"| {a} | {sum(r['verdict'] == 'same' for r in docs[a]['rows'])} of {len(docs[a]['rows'])} |" for a in AREAS]
    out += ['', f'| Area | Item | {ref} | {tgt} | Verdict | Adapter note | Evidence |', '|---|---|---|---|---|---|---|']
    for a in AREAS:
        for r in docs[a]['rows']:
            if r['verdict'] != 'same':
                out.append(f"| {a} | {_cell(r['item'])} | {_cell(r[paths.REFERENCE])} | {_cell(r[paths.TARGET])} | {r['verdict']} | "
                           f"{_cell(r['adapter'])} | {_cell(r['evidence'])} |")
    return '\n'.join(out) + '\n'


def _json(p):
    return json.loads(Path(p).read_text(encoding='utf-8'))


def readmes(root):
    """{README path: text} for every generated discovery README whose source file is committed."""
    _core(root)
    import assets
    import db
    import gate
    import loc
    import ui_atlas
    d = Path(root) / 'discovery'
    out = {d / 'diff' / 'README.md': render(root)}
    for sub, mod, src in (('assets', assets, 'summary.json'), ('db', db, 'tables.json'), ('loc', loc, 'summary.json'),
                          ('ui', ui_atlas, 'summary.json'), ('gate', gate, 'summary.json')):
        if (d / sub / src).exists():
            out[d / sub / 'README.md'] = mod.readme(_json(d / sub / src))
    return out


def readme_problems(root):
    """The committed READMEs that are not what their results render to."""
    return [f'{p}: stale; run `wsc discovery render`' for p, t in readmes(root).items() if not p.exists() or p.read_text(encoding='utf-8') != t]


def ui_problems(root):
    """The UI atlas: files as summary.json records them (sha256 of the JSON), deterministic gzip, rows and units in step."""
    _core(root)
    import ui_atlas
    d = Path(root) / 'discovery' / 'ui'
    if not (d / 'summary.json').exists():
        return []
    return ui_atlas.problems(str(d), str(Path(root) / 'registries' / 'ui_elements.jsonl'))


def j7_problems(root):
    """The asset, db and loc results: deterministic tables, the registry exactly what the committed index, refs and rules give, sheets and db shape."""
    paths = _core(root)
    import assets
    import tsvgz
    d = Path(root) / 'discovery'
    if not (d / 'assets' / 'index.tsv.gz').exists():
        return []
    bad = tsvgz.problems(str(d / 'assets' / 'index.tsv.gz'), assets.COLUMNS)
    if (d / 'loc' / 'keys.tsv.gz').exists():
        import loc
        bad += tsvgz.problems(str(d / 'loc' / 'keys.tsv.gz'), loc.COLUMNS)
    if bad:
        return bad
    index = assets.load_index(str(d / 'assets' / 'index.tsv.gz'))
    refs = _json(d / 'assets' / 'refs.json')['refs']
    reg = assets.read_registry(str(Path(root) / 'registries' / 'assets.jsonl'))
    want = assets.registry_rows(index, refs, assets.load_roles(str(Path(paths.ADAPTER) / 'asset_roles.json')), reg)
    if reg != want:
        ids = {r['id'] for r in reg} ^ {r['id'] for r in want}
        bad.append(f'registries/assets.jsonl: not in step with index.tsv.gz, refs.json and asset_roles.json ({len(reg)} rows, want '
                   f'{len(want)}; {len(ids)} ids differ); run `wsc discovery assets --stage registry` (or discovery/assets.py)')
    ids = {r['id'] for r in reg}
    if (d / 'assets' / 'sheets.json').exists():
        sh = _json(d / 'assets' / 'sheets.json')
        tiles = [t for s in sh['sheets'].values() for t in s['tiles']]
        if len(tiles) != len(set(tiles)) or not set(tiles) <= ids or any(len(s['tiles']) > 192 for s in sh['sheets'].values()):
            bad.append('discovery/assets/sheets.json: tiles repeat, exceed 192 a sheet or name ids not in the assets registry')
    if (d / 'db' / 'tables.json').exists():
        for t in _json(d / 'db' / 'tables.json')['tables']:
            if {'name', 'file', 'pack', 'version', 'rows', 'sha256', 'decoded'} - set(t) or (t['decoded'] is False and not t.get('reason')):
                bad.append(f"discovery/db/tables.json: {t.get('file')}: missing fields or a not-decoded table without a reason")
                break
    return bad


def _sub(root, *args):
    """Problems from one sibling `wsc` command: its output lines when it exits non-zero."""
    p = subprocess.run([sys.executable, str(CORE_ROOT / 'wsc.py')] + list(args), capture_output=True, text=True, cwd=root)
    return [] if p.returncode == 0 else ([x for x in (p.stdout + p.stderr).splitlines() if x.strip() and not x.startswith('ok ')][-12:] or [f'exit {p.returncode}'])


def _install(root):
    """--install: the PC comparison (read-only), as a callable for gate.run_gate."""
    paths = _core(root)
    import gate
    from pack_list import read_index
    games = _json(Path(paths.ADAPTER) / 'games.json')
    g = games[paths.TARGET]
    ident = _json(Path(paths.layout.proxy_adapter(Path(root))) / 'identity.json')
    summary = _json(Path(root) / 'discovery' / 'assets' / 'summary.json')
    return lambda: gate.install_problems(summary, g['root'], g['data'], ident['exe_name'], ident['sha1'], read_index)


def brief_gaps(root):
    """Every `## Registry gaps` bullet of every committed brief."""
    _core(root)
    import briefpaths
    out = []
    for p in sorted((Path(root) / 'jobs').glob('*/brief.md')):
        out += briefpaths.registry_gaps(p.read_text(encoding='utf-8'))[0]
    return out


def gate_run(root, install=False, write=False):
    """(lines, failures, doc) of the discovery gate; the recomputations run here, the slow sibling commands in parallel."""
    _core(root)
    import gate
    with ThreadPoolExecutor(max_workers=4) as ex:
        subs = {'reg check (schemas, rows, every tool has a row and a file)': ex.submit(_sub, root, 'reg', 'check'), 'hotkeys check': ex.submit(_sub, root, 'hotkeys', 'check'),
                'engine_sites table (gen_tables --check)': ex.submit(_gen_tables, root)}
        currency = {
            'discovery areas (J6)': lambda: _load(root)[1],
            'READMEs current': lambda: readme_problems(root),
            'assets registry in step with the index (J7)': lambda: j7_problems(root),
            'ui atlas files and rows (J10)': lambda: ui_problems(root),
        }
        currency.update({k: (lambda f=f: f.result()) for k, f in subs.items()})
        return gate.run_gate(root, currency, brief_gaps(root), _install(root) if install else None, write)


def _gen_tables(root):
    p = subprocess.run([sys.executable, str(CORE_ROOT / 'proxy' / 'tools' / 'gen_tables.py'), '--check'], capture_output=True, text=True, cwd=root)
    return [] if p.returncode == 0 else [x for x in (p.stdout + p.stderr).splitlines() if x.strip()][-12:]


def add_arguments(p):
    p.add_argument('action', choices=('check', 'render', 'gate', 'all') + ORDER)
    p.add_argument('--install', action='store_true', help='gate: also compare the installed packs and exe with the index and the pinned identity (PC, read-only)')
    p.add_argument('--write', action='store_true', help='gate: rewrite discovery/gate/summary.json first')
    p.add_argument('--json', metavar='OUT', help='gate: also write the report to this file')
    p.add_argument('rest', nargs='*', help='passed to the pass script (for example --stage registry)')


def run(args, ctx):
    root = Path(ctx.root)
    if args.action in PASSES or args.action == 'all':
        env = dict(os.environ, WSP_GAME_ROOT=str(root))   # the pass finds the game and its adapter through layout.py, not by its own place
        for a in (ORDER if args.action == 'all' else (args.action,)):
            cmd = [sys.executable, str(DISCOVERY / PASSES[a])] + list(args.rest)
            if subprocess.run(cmd, cwd=root, env=env).returncode:
                return 1
        if args.action in ('sheets',):
            return 0
        args.action = 'render'
    if args.action == 'render':
        for p, text in readmes(root).items():
            p.write_text(text, encoding='utf-8', newline='\n')
            print(f'{p}: {len(text.encode())} bytes')
        return 0
    if args.action == 'gate':
        lines, fails, _ = gate_run(root, args.install, args.write)
        print('\n'.join(lines))
        print('\n'.join(f'FAIL {f}' for f in fails) or 'discovery gate: ok')
        if args.json:
            Path(args.json).write_text(json.dumps({'lines': lines, 'failures': fails}, indent=1) + '\n', encoding='utf-8')
        return 1 if fails else 0
    _, bad = _load(root)
    if not bad:
        _, bad, _ = gate_run(root)
    print('\n'.join(bad) or 'discovery: 6 area files valid, J7 and J10 results in step, READMEs current, gate ok')
    return 1 if bad else 0
