class ValueRows(unittest.TestCase):
    def test_good_rows_render_and_round_trip(self):
        keys = [vkey(), vkey(id='gfx.grass', type='int', min=0, max=16)]
        sites = [vrow(value_scale=0.75, value_floor_stock=True), vrow(id='grass.n', rva='0x1200', anchor_bytes='b9', stock_bytes='05 00 00 00', value_key='gfx.grass'),
                 vrow(id='shadow.ext', rva='0x1300', stock_bytes='00 00 96 c2')]   # -75.0f: below stock is allowed without the floor
        self.assertEqual(errors(sites, keys), [])
        hdr = G.render_header(IDENT, sites, keys, 'proxy/golden')
        self.assertIn('configKey [, valueKey, valueType, valueFloorStock, valueScale]', hdr)
        self.assertIn('{ "dist.unit", kPatch, 0x1100u, 3, { 0xc7, 0x41, 0x48 }, 4, { 0x00, 0x00, 0xc8, 0x42 }, { 0 }, nullptr, "gfx.dist", kValueF32, 1, 0.75 },', hdr)
        self.assertIn('{ "grass.n", kPatch, 0x1200u, 1, { 0xb9 }, 4, { 0x05, 0x00, 0x00, 0x00 }, { 0 }, nullptr, "gfx.grass", kValueI32, 0, 1.0 },', hdr)

    def test_refusals(self):
        keys = [vkey(), vkey(id='gfx.untyped', type=None), vkey(id='gfx.name', type='string', default='', min=None, max=None),
                vkey(id='gfx.one', default=1, min=None), vkey(id='gfx.nomax', max=None), vkey(id='gfx.pos', min=10, max=600, default=10),
                vkey(id='gfx.neg', min=-150, max=-10, default=-10), {'id': 'gfx.on', 'type': 'bool', 'default': True, 'description': 'd', 'owner': 'o'},
                vkey(id='gfx.int', type='int')]
        cases = {
            'value_key gfx.missing is not in the config_keys registry': vrow(value_key='gfx.missing'),
            'has no explicit type': vrow(value_key='gfx.untyped'),
            'is a string key: a value row needs an int or float key': vrow(value_key='gfx.name'),
            'is a bool key': vrow(value_key='gfx.on'),
            'has default 1: it must be 0': vrow(value_key='gfx.one'),
            'has no max': vrow(value_key='gfx.nomax'),
            'gfx.pos range [10, 600] must contain 0': vrow(value_key='gfx.pos'),
            'gfx.neg range [-150, -10] must contain 0': vrow(value_key='gfx.neg'),
            'needs 4 stock bytes': vrow(stock_bytes='00 00 c8'),
            'are not a finite float32': vrow(stock_bytes='00 00 c0 7f'),   # NaN
            'value_scale and value_floor_stock belong to value_key rows': vrow(value_key=None, patch_bytes='00 00 48 43', value_scale=2),
            'value_scale and value_floor_stock belong': vrow(value_key=None, patch_bytes='00 00 48 43', value_floor_stock=True),
            'both config_key and value_key': vrow(config_key='gfx.on'),
            'both patch_bytes and value_key': vrow(patch_bytes='00 00 48 43'),
            'value_scale 0 must be a number above 0': vrow(value_scale=0),
            'value_key is for patch rows': vrow(kind='hook', hook='x', stock_bytes='55 8b ec 83'),
            'patch_bytes missing or not lowercase hex pairs (or give a value_key)': vrow(value_key=None),
        }
        for want, row in cases.items():
            with self.subTest(want=want):
                errs = G.validate_sites([row], keys, IDENT)
                self.assertTrue(any(want in e for e in errs), errs)
        self.assertEqual(G.validate_sites([vrow(value_key='gfx.int', stock_bytes='00 00 c8 42')], keys, IDENT), [])   # 1120403456 as int32

    def test_round_trip_refuses_a_lossy_encoding(self):
        orig = G.VALUE_TYPES['float']
        try:   # a codec that loses bytes (as a wrong width would): the round trip at --check time names the row
            G.VALUE_TYPES['float'] = ('<e', 'kValueF32')
            errs = G.validate_sites([vrow(stock_bytes='00 00 c8 42')], [vkey()], IDENT)
        except Exception as e:   # struct '<e' unpacks 2 bytes, so the 4-byte stock fails loudly too
            errs = [str(e)]
        finally:
            G.VALUE_TYPES['float'] = orig
        self.assertTrue(errs)
        self.assertEqual(G.validate_sites([vrow(stock_bytes='00 00 c8 42')], [vkey()], IDENT), [])

    def test_overlap_still_refused(self):
        errs = G.validate_sites([vrow(), vrow(id='dist.two', rva='0x1102')], [vkey()], IDENT)
        self.assertTrue(any('overlap' in e for e in errs), errs)


