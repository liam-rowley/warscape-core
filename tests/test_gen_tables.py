def vkey(**kw):
    k = {'id': 'gfx.dist', 'type': 'float', 'default': 0, 'min': 0, 'max': 600, 'description': 'd', 'owner': 'o'}
    k.update(kw)
    return {f: v for f, v in k.items() if v is not None}


def vrow(**kw):
    s = {'id': 'dist.unit', 'description': 'd', 'purpose': 'p', 'kind': 'patch', 'rva': '0x1100', 'anchor_bytes': 'c7 41 48',
         'stock_bytes': '00 00 c8 42', 'value_key': 'gfx.dist'}
    s.update(kw)
    return {f: v for f, v in s.items() if v is not None}


def errors(sites, keys):
    return G.validate_sites(sites, keys, IDENT) + [e for k in keys for e in G.validate_key(k)]


