def _load_gen():
    saved = os.environ.get('WSP_GAME_ROOT')
    os.environ['WSP_GAME_ROOT'] = str(NULL_GAME)
    try:
        spec = importlib.util.spec_from_file_location('gen_tables_w7', ROOT / 'proxy' / 'tools' / 'gen_tables.py')
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod
    finally:
        if saved is None:
            os.environ.pop('WSP_GAME_ROOT', None)
        else:
            os.environ['WSP_GAME_ROOT'] = saved


