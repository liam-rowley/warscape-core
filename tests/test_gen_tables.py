class RegistryLoader(unittest.TestCase):
    """W28: the generator reads engine_sites and config_keys through the core's registry loader, so `wsc reg migrate engine_sites --to dir`
    keeps it working and the generated files keep their bytes."""

    def generate(self, game):
        import subprocess
        env = {**os.environ, 'WSP_GAME_ROOT': str(game)}
        env.pop('WSP_PROXY_ADAPTER', None)
        (game / 'proxy' / 'null' / 'generated' / 'tables.h').unlink()
        p = subprocess.run([sys.executable, str(ROOT / 'proxy' / 'tools' / 'gen_tables.py')], env=env, capture_output=True, text=True)
        self.assertEqual(p.returncode, 0, p.stdout + p.stderr)
        return (game / 'proxy' / 'null' / 'generated' / 'tables.h').read_bytes()

    def test_dir_storage_gives_the_same_tables_bytes_as_jsonl(self):
        import contextlib
        import io
        import shutil
        import subprocess
        import tempfile
        from warscape.cli import main
        want = (NULL_GAME / 'proxy' / 'null' / 'generated' / 'tables.h').read_bytes()
        with tempfile.TemporaryDirectory() as td:
            game = Path(td).resolve() / 'game'
            shutil.copytree(NULL_GAME, game)
            self.assertEqual(self.generate(game), want)            # no wsc.toml: the default place, JSON Lines
            subprocess.run(['git', 'init', '-q', str(game)], check=True)
            (game / 'wsc.toml').write_text('[registries]\nengine_sites = "core:engine_sites"\nconfig_keys = "core:config_keys"\n'
                                           '[views]\ncommit = false\n', encoding='utf-8')
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(main(['--root', str(game), 'reg', 'migrate', 'engine_sites', '--to', 'dir']), 0)
            self.assertFalse((game / 'registries' / 'engine_sites.jsonl').exists())
            self.assertTrue((game / 'registries' / 'engine_sites').is_dir())
            self.assertEqual(self.generate(game), want)            # one file per row: the same bytes


class TypedKeys(unittest.TestCase):
    def test_float_key_renders_with_range_and_repr(self):
        k = vkey(release_value=250)
        self.assertEqual(G.key_type(k), ('kFloat', '0.0'))
        hdr = G.render_header(IDENT, [], [k, vkey(id='gfx.free', min=None, max=None), vkey(id='gfx.top', min=None)], 'proxy/golden')
        self.assertIn('{ "gfx.dist", kFloat, "0.0", "0.0", "600.0" },', hdr)
        self.assertIn('{ "gfx.free", kFloat, "0.0" },', hdr)
        self.assertIn('{ "gfx.top", kFloat, "0.0", nullptr, "600.0" },', hdr)
        self.assertIn('dist=250.0\r\n', G.render_ini(IDENT, [k]))
        self.assertIn('(default 0.0)', G.render_ini(IDENT, [k]))

    def test_int_key_range(self):
        k = vkey(id='gfx.grass', type='int', min=-5, max=16, release_value=9)
        self.assertEqual(errors([], [k]), [])
        self.assertIn('{ "gfx.grass", kInt, "0", "-5", "16" },', G.render_header(IDENT, [], [k], 'proxy/golden'))

    def test_key_refusals(self):
        cases = {
            'type \'double\'': vkey(type='double'),
            'default 1.5 is not a valid int': vkey(type='int', default=1.5),
            'does not fit int32': vkey(type='int', default=2**31, min=None, max=None),
            'release_value \'far\' is not a valid float': vkey(release_value='far'),
            'is not a finite float32': vkey(max=1e39),
            'min and max are for int and float keys': vkey(type='bool', default=False),
            'min 700 is above max 600': vkey(min=700, default=700),
            'release_value 900 is outside': vkey(release_value=900),
            'default -1 is outside': vkey(default=-1),
            'only bool, int and string defaults infer a type': {'id': 'a.f', 'default': 1.5, 'description': 'd', 'owner': 'o'},
            'ids are <section>.<key>': vkey(id='nodot'),
        }
        for want, k in cases.items():
            with self.subTest(want=want):
                errs = G.validate_key(k)
                self.assertTrue(any(want in e for e in errs), errs)


class ValueRows(unittest.TestCase):
    def test_good_rows_render_and_round_trip(self):
        keys = [vkey(), vkey(id='gfx.grass', type='int', min=0, max=16)]
        sites = [vrow(value_scale=0.75, value_floor_stock=True), vrow(id='grass.n', rva='0x1200', anchor_bytes='b9', stock_bytes='05 00 00 00', value_key='gfx.grass'),
                 vrow(id='shadow.ext', rva='0x1300', stock_bytes='00 00 96 c2')]   # -75.0f: below stock is allowed without the floor
        self.assertEqual(errors(sites, keys), [])
        hdr = G.render_header(IDENT, sites, keys, 'proxy/golden')
        self.assertIn('configKey [, valueKey, valueType, valueFloorStock, valueScale]', hdr)
        self.assertIn('{ "dist.unit", kPatch, 0x1100u, 3, { 0xc7, 0x41, 0x48 }, 4, { 0x00, 0x00, 0xc8, 0x42 }, { 0 }, nullptr, "gfx.dist", kValueF32, 1, 0.75 },', hdr)
        self.assertIn('{ "grass.n", kPatch, 0x1200u, 1, { 0xb9 }, 4, { 0x05, 0x00, 0x00, 0x00 }, { 0 }, nullptr, "gfx.grass", kValueI32, 0, 1.0 },', hdr)

    def test_refusals(self):
        keys = [vkey(), vkey(id='gfx.untyped', type=None), vkey(id='gfx.name', type='string', default='', min=None, max=None),
                vkey(id='gfx.one', default=1, min=None), vkey(id='gfx.nomax', max=None), vkey(id='gfx.pos', min=10, max=600, default=10),
                vkey(id='gfx.neg', min=-150, max=-10, default=-10), {'id': 'gfx.on', 'type': 'bool', 'default': True, 'description': 'd', 'owner': 'o'},
                vkey(id='gfx.int', type='int')]
        cases = {
            'value_key gfx.missing is not in the config_keys registry': vrow(value_key='gfx.missing'),
            'has no explicit type': vrow(value_key='gfx.untyped'),
            'is a string key: a value row needs an int or float key': vrow(value_key='gfx.name'),
            'is a bool key': vrow(value_key='gfx.on'),
            'has default 1: it must be 0': vrow(value_key='gfx.one'),
            'has no max': vrow(value_key='gfx.nomax'),
            'gfx.pos range [10, 600] must contain 0': vrow(value_key='gfx.pos'),
            'gfx.neg range [-150, -10] must contain 0': vrow(value_key='gfx.neg'),
            'needs 4 stock bytes': vrow(stock_bytes='00 00 c8'),
            'are not a finite float32': vrow(stock_bytes='00 00 c0 7f'),   # NaN
            'value_scale and value_floor_stock belong to value_key rows': vrow(value_key=None, patch_bytes='00 00 48 43', value_scale=2),
            'value_scale and value_floor_stock belong': vrow(value_key=None, patch_bytes='00 00 48 43', value_floor_stock=True),
            'both config_key and value_key': vrow(config_key='gfx.on'),
            'both patch_bytes and value_key': vrow(patch_bytes='00 00 48 43'),
            'value_scale 0 must be a number above 0': vrow(value_scale=0),
            'value_key is for patch rows': vrow(kind='hook', hook='x', stock_bytes='55 8b ec 83'),
            'patch_bytes missing or not lowercase hex pairs (or give a value_key)': vrow(value_key=None),
        }
        for want, row in cases.items():
            with self.subTest(want=want):
                errs = G.validate_sites([row], keys, IDENT)
                self.assertTrue(any(want in e for e in errs), errs)
        self.assertEqual(G.validate_sites([vrow(value_key='gfx.int', stock_bytes='00 00 c8 42')], keys, IDENT), [])   # 1120403456 as int32

    def test_round_trip_refuses_a_lossy_encoding(self):
        orig = G.VALUE_TYPES['float']
        try:   # a codec that loses bytes (as a wrong width would): the round trip at --check time names the row
            G.VALUE_TYPES['float'] = ('<e', 'kValueF32')
            errs = G.validate_sites([vrow(stock_bytes='00 00 c8 42')], [vkey()], IDENT)
        except Exception as e:   # struct '<e' unpacks 2 bytes, so the 4-byte stock fails loudly too
            errs = [str(e)]
        finally:
            G.VALUE_TYPES['float'] = orig
        self.assertTrue(errs)
        self.assertEqual(G.validate_sites([vrow(stock_bytes='00 00 c8 42')], [vkey()], IDENT), [])

    def test_overlap_still_refused(self):
        errs = G.validate_sites([vrow(), vrow(id='dist.two', rva='0x1102')], [vkey()], IDENT)
        self.assertTrue(any('overlap' in e for e in errs), errs)


class Schemas(unittest.TestCase):
    sites = json.loads((ROOT / 'schemas' / 'engine_sites.schema.json').read_text(encoding='utf-8'))
    keys = json.loads((ROOT / 'schemas' / 'config_keys.schema.json').read_text(encoding='utf-8'))

    def test_schemas_are_valid(self):
        self.assertEqual(check_schema(self.sites), [])
        self.assertEqual(check_schema(self.keys), [])

    def test_engine_site_rules(self):
        ok = vrow(value_scale=0.75, value_floor_stock=True)
        self.assertEqual(validate(ok, self.sites), [])
        self.assertEqual(validate(dict(OLD_SITES[0], description='d', purpose='p'), self.sites), [])
        for bad in (vrow(patch_bytes='00 00 48 43'), vrow(value_key=None), vrow(config_key='gfx.on'), vrow(value_scale=0),
                    vrow(value_key=None, patch_bytes='00 00 48 43', value_floor_stock=True), vrow(kind='hook', hook='x')):
            with self.subTest(bad=bad):
                self.assertNotEqual(validate(bad, self.sites), [])

    def test_config_key_rules(self):
        self.assertEqual(validate(vkey(), self.keys), [])
        self.assertEqual(validate(OLD_KEYS[0], self.keys), [])
        for bad in (vkey(type='double'), vkey(type=None), vkey(type='string'), vkey(max='600')):
            with self.subTest(bad=bad):
                self.assertNotEqual(validate(bad, self.keys), [])


