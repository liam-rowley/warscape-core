        sites = [json.loads(x) for x in (NULL_GAME / 'registries' / 'engine_sites.jsonl').read_text(encoding='utf-8').splitlines() if x.strip()]
        keys = [json.loads(x) for x in (NULL_GAME / 'registries' / 'config_keys.jsonl').read_text(encoding='utf-8').splitlines() if x.strip()]
