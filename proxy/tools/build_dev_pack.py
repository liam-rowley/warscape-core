#!/usr/bin/env python3
"""Build the dev wrapper pack (dev.lua_bridge): one wrapper script per line of proxy/<adapter>/lua/wrappers.txt, as a PFH0 movie pack.

purpose: generate the wrapper chunks (each runs the vanilla script through <mod_dir>/lua/wsp.lua and pumps the Lua bridge)
         and write them, deterministically, into build/proxy/<adapter>/zz_<mod>_dev.pack (the proxy lists it in data\\ virtually)
usage: python3 proxy/tools/build_dev_pack.py [--adapter DIR] [--out FILE] [--list]   (DIR: the proxy adapter folder, default proxy/tools/layout.py proxy-adapter)
when: pc_deploy.py kit runs it (the pack ships in the kit as <mod>/packs/); after any change to wrappers.txt or the wrapper template
not-a-verb: writes a game-format binary from repo sources; pc_deploy.py calls it

The pack is type 4 (a movie pack: the engine loads every one it lists in data\\; empire-remastered zz_rml.pack, same format). Entries
are plain Lua source under the vanilla .luac name, as the engine loads them (empire-remastered build_rml_pack.py). Whether this pack
beats the vanilla data.pack entry is checked per game by its PC survey (the game repo's engine fact packs.dev_pack_precedence).
"""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import layout  # noqa: E402

ROOT = layout.game_root()
TEMPLATE = """-- GENERATED by proxy/tools/build_dev_pack.py from {adapter}/lua/wrappers.txt - dev only (dev.lua_bridge, J3).
-- Wrapper for the vanilla {entry} (context {ctx}): the vanilla script runs unchanged (wsp.vanilla), then its update callback
-- also pumps the proxy's Lua bridge. Without the proxy's dev keys this pack is not listed at all.
return dofile("{luadir}wsp.lua").wrap("{entry_lua}", "{ctx}", getfenv(1){inject})
"""


def wrappers(adapter):
    out = []
    for n, line in enumerate((Path(adapter) / 'lua' / 'wrappers.txt').read_text(encoding='utf-8').splitlines(), 1):
        s = line.strip()
        if not s or s.startswith('#'):
            continue
        if '|' not in s:
            raise SystemExit(f'build_dev_pack: wrappers.txt line {n}: expected "<entry> | <context>"')
        parts = [x.strip() for x in s.split('|')]
        entry, ctx, opt = parts[0], parts[1], parts[2] if len(parts) > 2 else ''
        if opt not in ('', 'main_after_reset'):
            raise SystemExit(f'build_dev_pack: wrappers.txt line {n}: option {opt!r} is not main_after_reset')
        if ctx not in ('frontend', 'campaign', 'battle'):
            raise SystemExit(f'build_dev_pack: wrappers.txt line {n}: context {ctx!r} is not frontend, campaign or battle')
        out.append((entry.lower().replace('/', '\\'), ctx, opt))
    return out


def build(adapter=None, out=None):
    adapter = Path(adapter).resolve() if adapter else layout.proxy_adapter(ROOT)
    ident = json.loads((adapter / 'identity.json').read_text(encoding='utf-8'))
    mod = ident['mod_dir']
    out = Path(out or ROOT / 'build' / 'proxy' / adapter.name / f'zz_{mod}_dev.pack')
    entries = []
    for entry, ctx, opt in wrappers(adapter):
        text = TEMPLATE.format(adapter=adapter.relative_to(ROOT).as_posix() if adapter.is_relative_to(ROOT) else adapter.name, entry=entry, ctx=ctx, luadir=f'{mod}/lua/', entry_lua=entry.replace('\\', '\\\\'), inject=f', "{opt}"' if opt else '')
        entries.append((entry, text.encode('ascii')))
    index = b''.join(struct.pack('<I', len(d)) + p.encode('latin-1') + b'\0' for p, d in entries)
    blob = b'PFH0' + struct.pack('<IIIII', 4, 0, 0, len(entries), len(index)) + index + b''.join(d for _, d in entries)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(blob)
    print(f'build_dev_pack: {out} ({len(entries)} wrappers, sha256 {hashlib.sha256(blob).hexdigest()[:16]})')
    return out, entries


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--adapter', help='the proxy adapter folder (default: layout.py proxy-adapter)')
    ap.add_argument('--out')
    ap.add_argument('--list', action='store_true')
    a = ap.parse_args(argv)
    _, entries = build(a.adapter, a.out)
    if a.list:
        for p, d in entries:
            print(f'{len(d):6} {p}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
