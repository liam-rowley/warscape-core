// ------------------------------------------------------------------------------------------------ 5. the camera, the ray pick, the projection
static Camera Cam(V3 pos, V3 target, double w = 1920, double h = 1080, double fov = 70.0) { Camera c; c.pos = pos; c.target = target; c.fovYDeg = fov; c.w = w; c.h = h; return c; }
static void Pick() {
    double vp[16];
    Camera c = Cam(V3{ 10, 40, -60 }, V3{ 10, 0, 20 });
    Check(CameraVP(c, vp), "cam: a battle pose inverts");
    {   double px = 0, py = 0; WorldToScreen(c.target, vp, c.w, c.h, &px, &py);
        Check(Close(px, c.w / 2 - 0.5, 1e-6) && Close(py, c.h / 2 - 0.5, 1e-6), "cam: the target projects to the screen centre (pixel-centre convention)"); }
    {   // 70 degrees vertical: a point 35 degrees above the axis lands on the top edge (NDC y = 1 -> py = -0.5)
        const double l = std::hypot(80.0, 40.0), ax = 0, ay = -40.0 / l, az = 80.0 / l;   // axis (unit)
        const double up[3] = { 0, 80.0 / l, 40.0 / l };                                    // camera up, perpendicular to the axis
        const double t = std::tan(Rad(35.0)), d = 50.0;
        const V3 p{ c.pos.x + d * (ax + t * up[0]), c.pos.y + d * (ay + t * up[1]), c.pos.z + d * (az + t * up[2]) };
        double px = 0, py = 0; WorldToScreen(p, vp, c.w, c.h, &px, &py);
        Check(Close(py, -0.5, 1e-6) && Close(px, c.w / 2 - 0.5, 1e-6), "cam: half the vertical field of view reaches the top edge"); }
    Check(!CameraVP(Cam(V3{ 0, 50, 0 }, V3{ 0, 0, 0 }), vp), "cam: straight down has no yaw: refused");
    Check(!CameraVP(Cam(V3{ 1, 1, 1 }, V3{ 1, 1, 1 }), vp), "cam: eye on the target refused");
    Check(!CameraVP(Cam(V3{ 0, 10, 0 }, V3{ 0, 0, 10 }, 1920, 0), vp), "cam: an empty client refused");
    Check(!CameraVP(Cam(V3{ 0, 10, 0 }, V3{ 0, 0, 10 }, 1920, 1080, 0.5), vp), "cam: a field of view under 1 degree refused");
    Check(!CameraVP(Cam(V3{ NAN, 10, 0 }, V3{ 0, 0, 10 }), vp), "cam: non-finite refused");
    CameraVP(c, vp);
    auto flat = [](double, double, double* y) { *y = 2.0; return true; };
    auto slope = [](double x, double z, double* y) { *y = 0.08 * x + 0.05 * z; return true; };   // a gentle hill (under 5 degrees)
    auto offMap = [](double, double, double*) { return false; };
    double worst = 0, worstRes = 0; int n = 0;
    for (int ix = 1; ix < 10; ++ix) for (int iy = 4; iy < 10; ++iy) {
        const double px = c.w * ix / 10.0, py = c.h * iy / 10.0;
        V3 a, b; double ra = -1, rb = -1;
        Check(PickGround(px, py, 0.0, vp, c.w, c.h, flat, 3, &a, &ra) && Close(a.y, 2.0, 1e-9) && ra < 1e-9, "pick: flat ground at 2 m, plane at 0 m: one refinement lands on it");
        Check(PickGround(px, py, 0.0, vp, c.w, c.h, slope, 12, &b, &rb), "pick: sloped ground");
        double sx = 0, sy = 0; WorldToScreen(b, vp, c.w, c.h, &sx, &sy);
        worst = std::max(worst, std::hypot(sx - px, sy - py)); worstRes = std::max(worstRes, rb); ++n;
        double gy = 0; slope(b.x, b.z, &gy);
        double dx = 0, dy = 0; WorldToScreen(V3{ b.x, gy, b.z }, vp, c.w, c.h, &dx, &dy);
        Check(std::hypot(dx - px, dy - py) <= 1.0, "pick: the draped ground point under the pick projects within 1 px of the cursor");
    }
    Check(n == 54 && worst < 1e-6, "pick: every picked point projects back onto its cursor pixel (54 points, < 1e-6 px)");
    if (worstRes >= 0.05) printf("    worst residual %.4f m\n", worstRes);
    Check(worstRes < 0.05, "pick: twelve refinements sit the pick on a 5 degree slope within 5 cm (the far corners converge slowest)");
    {   V3 s; Check(!PickGround(c.w / 2, 0.0, 0.0, vp, c.w, c.h, flat, 3, &s), "pick: the sky (the top row over a 27 degree down look) misses"); }
    {   V3 a; double r = 0; Check(PickGround(c.w / 2, c.h * 0.9, 0.0, vp, c.w, c.h, offMap, 3, &a, &r) && r == -1, "pick: no ground height: the plane hit is kept, residual -1"); }
    // the projection round trip: world -> pixel -> plane pick at the point's own height -> the same world point
    double worstRt = 0;
    for (double x = -60; x <= 80; x += 20) for (double z = 10; z <= 150; z += 20) {
        const V3 p{ x, 0.05 * z - 1.0, z }; double px = 0, py = 0;
        if (!WorldToScreen(p, vp, c.w, c.h, &px, &py)) continue;
        V3 q; if (!PickPlane(px, py, p.y, vp, c.w, c.h, &q)) { worstRt = 1e9; continue; }
        double qx = 0, qy = 0; WorldToScreen(q, vp, c.w, c.h, &qx, &qy);
        worstRt = std::max(worstRt, std::max(std::hypot(q.x - p.x, q.z - p.z), std::hypot(qx - px, qy - py)));
    }
    Check(worstRt < 1e-6, "projection round trip: world -> pixel -> pick -> pixel within 1e-6 (metres and px)");
}

