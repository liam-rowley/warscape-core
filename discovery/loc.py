#!/usr/bin/env python3
"""Loc pass: decode every .loc file byte-exact, commit the keys (never the text) and tie key prefixes to db tables.

purpose: decode Warscape .loc string tables (byte-exact) and write discovery/loc/keys.tsv.gz (file, key, text length, text sha1, flag, patch state) and summary.json; the text goes to /extract/<target>/loc/
usage: python3 discovery/loc.py [--games <adapter>/games.json]   (or `wsc discovery loc`)   |   from loc import decode, encode
when: J7; re-run after a game update; the db pass (db.py) should run first so the prefix cross-check sees the db schema
not-a-verb: reads the game's language packs in place on the PC; `wsc discovery loc` runs it

Layout (checked on the target game 2026-10-29): u16 BOM FF FE, 'LOC\\0', u32 version, u32 entry count; per entry a key and a text (each
u16 character count + UTF-16LE) and a u8 flag. A decode counts only when it consumes every byte.
"""
import argparse
import collections
import hashlib
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import paths  # noqa: E402
REPO = paths.REPO
import tsvgz  # noqa: E402
from packfs import PackFS, key  # noqa: E402

GAME = paths.TARGET
OUT = os.path.join(REPO, 'discovery', 'loc')
KEYS = os.path.join(OUT, 'keys.tsv.gz')
SUMMARY = os.path.join(OUT, 'summary.json')
TEXT = os.path.join(REPO, 'extract', GAME, 'loc')
COLUMNS = ('file', 'key', 'text_len', 'text_sha1', 'flag', 'patch')
MAGIC = b'\xff\xfeLOC\x00'


def decode(b):
    """(version, [(key, text, flag)]); raises ValueError unless the entries consume every byte."""
    if b[:6] != MAGIC:
        raise ValueError(f'not a .loc file (starts {b[:6].hex(" ")})')
    version, count = struct.unpack_from('<II', b, 6)
    o, out = 14, []
    try:
        for _ in range(count):
            vals = []
            for _ in range(2):
                n = struct.unpack_from('<H', b, o)[0] * 2
                if o + 2 + n > len(b):
                    raise ValueError(f'string overrun at {o}')
                vals.append(b[o + 2:o + 2 + n].decode('utf-16-le'))
                o += 2 + n
            out.append((vals[0], vals[1], b[o]))
            o += 1
    except (struct.error, IndexError):
        raise ValueError(f'truncated at {o} of {len(b)} bytes after {len(out)} of {count} entries')
    if o != len(b):
        raise ValueError(f'consumed {o} of {len(b)} bytes ({count} entries)')
    return version, out


def encode(version, entries):
    s = lambda t: struct.pack('<H', len(t.encode('utf-16-le')) // 2) + t.encode('utf-16-le')
    return MAGIC + struct.pack('<II', version, len(entries)) + b''.join(s(k) + s(t) + bytes([f]) for k, t, f in entries)


def db_tables(fs):
    """db table names (folder name without _tables) from the install, and {table: field names} from the committed schema."""
    names = {key(c.path).split('\\')[1][:-7] for c in fs.list(under='db\\') if key(c.path).split('\\')[1].endswith('_tables')}
    fields = {}
    try:
        sch = json.load(open(paths.adapter_file('db_schema.json'), encoding='utf-8'))['tables']
        fields = {t[:-7]: {f['name'] for v in vs for f in v['fields']} for t, vs in sch.items()}
    except (OSError, ValueError, KeyError):
        pass
    return names, fields


def table_of(k, tables):
    """Longest db table name t with k starting 't_' (the <table>_<field>_<row key> shape); None if no table fits."""
    best = None
    for t in tables:
        if k.startswith(t + '_') and (best is None or len(t) > len(best)):
            best = t
    return best


def readme(s):
    out = [f'# {paths.titled(paths.TARGET)} loc keys (J7)', '',
           'Generated by `python3 core/wsc.py discovery render` from `summary.json` (written by `discovery/core/loc.py`). Do not edit.',
           f'Keys only: `keys.tsv.gz` (file, key, text length, text sha1, flag, patch state). Text: `/extract/{paths.TARGET}/loc/`.', '',
           '| File | Pack | Version | Entries | Patch: same / changed / new | Removed by patch | Flags |', '|---|---|---|---|---|---|---|']
    for f, d in s['files'].items():
        p = d['patch']
        out.append(f"| {f} | {d['source']} | {d['version']} | {d['entries']} | {p.get('same', 0)} / {p.get('changed', 0)} / "
                   f"{p.get('new', 0)} | {d['removed_by_patch']} | {', '.join(f'{k}: {v}' for k, v in d['flags'].items())} |")
    out += ['', f"Prefix cross-check: {s['keys_with_db_table']} of {s['keys']} keys start `<db table>_` for one of the "
            f"{s['db_tables_known']} db tables" + (f", {s['keys_with_db_field']} of them followed by a field of that table in the schema"
                                                     if s['schema_fields_known'] else ' (no db schema committed, so fields are not checked)')
            + f"; {s['keys_without_db_table']} keys name no db table (mostly ui.loc component strings).", '',
            '| Table | Keys |' + (' Field matched |' if s['schema_fields_known'] else ''), '|---|---|' + ('---|' if s['schema_fields_known'] else '')]
    top = sorted(s['per_table'].items(), key=lambda x: (-x[1]['keys'], x[0]))[:40]
    out += [f"| {t} | {d['keys']} |" + (f" {d.get('field_matched', 0)} |" if s['schema_fields_known'] else '') for t, d in top]
    out += ['', 'Keys with no db table, by first token (top 60): '
            + ', '.join(f'`{k or "(empty)"}` {v}' for k, v in s['without_table_by_first_token'].items()) + '.']
    return '\n'.join(out) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--games', default=paths.adapter_file('games.json'))
    a = ap.parse_args(argv)
    fs = PackFS.from_games(json.load(open(a.games, encoding='utf-8')), GAME)
    by_file = collections.defaultdict(list)
    for c in fs.copies():
        if c.path.lower().endswith('.loc'):
            by_file[key(c.path)].append(c)
    tables, fields = db_tables(fs)
    rows, files, prefixes, no_table = [], {}, collections.Counter(), collections.Counter()
    field_hits = collections.Counter()
    os.makedirs(TEXT, exist_ok=True)
    for f, cs in sorted(by_file.items()):
        eff = next(c for c in cs if c.effective)
        base = [c for c in cs if not c.effective]
        version, ents = decode(fs.read(eff))
        old = {}
        for c in base:
            old.update({k: t for k, t, _ in decode(fs.read(c))[1]})
        seen = collections.Counter(k for k, _, _ in ents)
        st = collections.Counter()
        with open(os.path.join(TEXT, f.replace('\\', '_') + '.tsv'), 'w', encoding='utf-8', newline='\n') as out:
            for k, t, flag in ents:
                out.write(f'{k}\t{tsvgz.cell(t)}\n')
                patch = '' if not base else 'new' if k not in old else 'same' if old[k] == t else 'changed'
                st[patch or 'unpatched'] += 1
                rows.append((f, k, len(t), hashlib.sha1(t.encode('utf-8')).hexdigest(), flag, patch))
                tb = table_of(k, tables)
                if tb:
                    prefixes[tb] += 1
                    rest = k[len(tb) + 1:]
                    if tb in fields and any(rest.startswith(x + '_') for x in fields[tb]):
                        field_hits[tb] += 1
                else:
                    no_table[k.split('_', 1)[0]] += 1
        files[f] = {'source': eff.source, 'version': version, 'entries': len(ents), 'bytes': eff.size,
                    'replaced_from': sorted(c.source for c in base), 'patch': dict(sorted(st.items())),
                    'removed_by_patch': len(set(old) - set(seen)), 'duplicate_keys': sum(n - 1 for n in seen.values() if n > 1),
                    'flags': {str(k): v for k, v in sorted(collections.Counter(fl for _, _, fl in ents).items())}}
    os.makedirs(OUT, exist_ok=True)
    n = tsvgz.write(KEYS, COLUMNS, set(rows))
    s = {'schema': 1, 'keys': len(rows), 'files': files,
         'db_tables_known': len(tables), 'schema_fields_known': bool(fields),
         'keys_with_db_table': sum(prefixes.values()), 'keys_with_db_field': sum(field_hits.values()),
         'per_table': {t: {'keys': prefixes[t], **({'field_matched': field_hits[t]} if fields else {})} for t in sorted(prefixes)},
         'keys_without_db_table': sum(no_table.values()),
         'without_table_by_first_token': dict(sorted(no_table.items(), key=lambda x: (-x[1], x[0]))[:60])}
    with open(SUMMARY, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(s, fh, indent=1, sort_keys=True)
        fh.write('\n')
    print(f'{KEYS}: {n} rows; {s["keys_with_db_table"]} keys tie to a db table, {s["keys_without_db_table"]} do not')
    return 0


if __name__ == '__main__':
    sys.exit(main())
